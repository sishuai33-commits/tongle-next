"""Explicit, bounded recovery after an operator-reviewed root fix.

Prepare binds original bytes; apply transfers responsibility without erasing
history; verify requires actual successor completion. No model calls here.
Generated by Pi/K3 and integrated against the real core APIs by Codex.
"""
import json
import time

from . import delta_migration as m

_PROTOCOL = "failed-recovery-v1"
_AUDIT_CHILD = "failed_recovery_child_v1"
_AUDIT_PARENT = "failed_recovery_parent_v1"
_BLOCKED_AUDITS = ("completion", "delta_complete_v1",
                   "delta_operator_intent_v1", "delta_operator_complete_v1")


def _fail(msg):
    raise ValueError(msg)


def _row(evo, work_id):
    r = evo.db.execute("SELECT * FROM knowledge_work WHERE id=?", (work_id,)).fetchone()
    return dict(r) if r is not None else None


def _audits(evo, work_id, state):
    rows = evo.db.execute(
        "SELECT rowid,* FROM knowledge_failures WHERE work_id=? AND state=? ORDER BY rowid",
        (work_id, state)).fetchall()
    return [dict(r) for r in rows]


def _has_audit(evo, work_id, state):
    return evo.db.execute(
        "SELECT 1 FROM knowledge_failures WHERE work_id=? AND state=? LIMIT 1",
        (work_id, state)).fetchone() is not None


def _calls_hash(evo, work_id):
    rows = evo.db.execute(
        "SELECT * FROM knowledge_calls WHERE work_id=? ORDER BY id", (work_id,)).fetchall()
    return m._hash([dict(r) for r in rows])


def _failures_hash(evo, work_id):
    rows = evo.db.execute(
        "SELECT rowid,* FROM knowledge_failures WHERE work_id=? ORDER BY rowid",
        (work_id,)).fetchall()
    return m._hash([dict(r) for r in rows])


# Columns a sanctioned post-transfer reclamation is ALLOWED to clear.
#
# ``apply`` still preserves them byte-for-byte (the transfer itself must not
# erase history), but once the duty has moved to the successor the stage cache
# has no remaining consumer -- the durable record is the audit rows below -- and
# the bounded ``tongle/reclaim.py`` sweep drops it from obsoleted rows on the
# next maintenance cycle. Binding it into the preservation hash would therefore
# make EVERY recovery fail ``verify`` as soon as that sweep ran, which is not a
# statement about the transfer's integrity. The hash still binds identity,
# project/session/protocol, inputs, attempts, error, timestamps, succession
# depth and every other column, so a rewritten parent is still detected.
_RECLAIMABLE_COLUMNS = ("bundle", "proposal", "review")


def _preserved_sha(row):
    d = dict(row)
    for k in ("state", "lease_token", "lease_until") + _RECLAIMABLE_COLUMNS:
        d.pop(k, None)
    return m._hash(d)


def _part_key(p):
    if isinstance(p, dict) and "part" in p:
        return p["part"]
    return p


def _validate_request(req):
    if not isinstance(req, dict) or set(req) != {"grant_id", "code_sha", "acceptance_sha", "work_ids"}:
        _fail("bad request keys")
    gid = req["grant_id"]
    if not isinstance(gid, str) or not m._is_slug(gid) or len(gid) > 128:
        _fail("bad grant_id")
    for k in ("code_sha", "acceptance_sha"):
        v = req[k]
        if not isinstance(v, str) or len(v) != 64 or not m._is_hex(v):
            _fail("bad " + k)
    wids = req["work_ids"]
    if not isinstance(wids, list) or not 1 <= len(wids) <= 150:
        _fail("bad work_ids")
    if any(not isinstance(w, str) or not w or len(w) > 128 for w in wids):
        _fail("bad work id")
    if len(set(wids)) != len(wids):
        _fail("duplicate work ids")
    return {"grant_id": gid, "code_sha": req["code_sha"],
            "acceptance_sha": req["acceptance_sha"], "work_ids": sorted(wids)}


def _check_gates(evo, row):
    pid = row["id"]
    if row["state"] != "failed":
        _fail("parent not failed: " + pid)
    if row["lease_token"] and (row["lease_until"] or 0) > time.time():
        _fail("live lease: " + pid)
    if evo.db.execute("SELECT 1 FROM knowledge_batches WHERE batch_id=?", (pid,)).fetchone():
        _fail("parent has committed batch: " + pid)
    if evo.db.execute(
            "SELECT 1 FROM knowledge_calls WHERE work_id=? AND elapsed IS NULL LIMIT 1",
            (pid,)).fetchone():
        _fail("unsettled calls: " + pid)
    for st in _BLOCKED_AUDITS + (_AUDIT_CHILD, _AUDIT_PARENT):
        if _has_audit(evo, pid, st):
            _fail("blocked audit %s: %s" % (st, pid))
    if row["pipeline_protocol"] not in (m.V2_PROTOCOL, m.LEGACY_PROTOCOL):
        _fail("bad protocol: " + pid)


def _prepare_entry(evo, parent_id):
    row = _row(evo, parent_id)
    if row is None:
        _fail("missing parent: " + parent_id)
    _check_gates(evo, row)
    protocol = row["pipeline_protocol"]
    project, session = row["project"], row["session"]
    inputs = json.loads(row["inputs"])
    if not isinstance(inputs, list) or not inputs or any(not isinstance(i, dict) for i in inputs):
        _fail("bad inputs: " + parent_id)
    sids = {i.get("source_id") for i in inputs}
    if any(not isinstance(sid, str) or not sid for sid in sids):
        _fail("invalid source identity")
    max_sources = 1 if protocol == m.V2_PROTOCOL else 8
    if not 1 <= len(sids) <= max_sources or len(inputs) > 16:
        _fail("source or part count out of bounds")
    sources, parts, text_chars = [], [], 0
    for sid in sorted(sids):
        source = dict(m._source_guard(evo, sid))
        m._check_source_identity(source, project, session)
        text = source.get('text')
        if protocol == m.V2_PROTOCOL:
            m._source_eligible(evo, source)
        elif not (session == "knowledge-dependency" and source.get("role") == "assistant"
                  and source.get("kind") == "event" and isinstance(text, str)
                  and 1 <= len(text) <= 32000):
            _fail("legacy source constraints: " + parent_id)
        text_chars += len(text)
        real = list(evo._source_parts(source))
        m._validate_inputs(evo, [p for p in inputs if p['source_id'] == sid], real)
        sources.append(source)
        parts.extend(real)
    if text_chars > 32000 or not 1 <= len(parts) <= 16:
        _fail("total source/parts exceeds recovery bound")
    expect = sorted((p['source_id'], p['version'], p['part']) for p in parts)
    seen = evo.db.execute(
        "SELECT source_id,version,part FROM knowledge_seen WHERE work_id=?",
        (parent_id,)).fetchall()
    claims = sorted((r["source_id"], r["version"], r["part"]) for r in seen)
    if claims != expect:
        _fail("claims mismatch: " + parent_id)
    claim_sigs = sorted(m._hash(list(c)) for c in claims)
    part_sigs = sorted((m._part_signature(p) for p in parts),
                       key=lambda p: (p['source_id'], p['version'], p['part']))
    mandatory = {}
    if protocol == m.LEGACY_PROTOCOL:
        rel = evo._related(project, inputs, {})
        if rel.get("required_problems") or rel.get("unresolved_required"):
            _fail("unresolved required: " + parent_id)
        mand = list(rel.get("mandatory") or [])
        cards = {c["id"]: c for c in (rel.get("cards") or [])}
        if any(cid not in cards for cid in mand):
            _fail("mandatory missing from cards: " + parent_id)
        known = set()
        for a in (evo._accepted_origin_audit(parent_id) or []):
            t = a.get("target") or {}
            p2 = a.get("pair") or {}
            for cid in (t.get("card_id"), t.get("id"), p2.get("card_id")):
                if cid:
                    known.add(cid)
        if any(cid not in mand for cid in known):
            _fail("known id not mandatory: " + parent_id)
        mandatory = {cid: m._hash(cards[cid]) for cid in sorted(mand)}
    inputs_sha = m._hash(inputs)
    child_id = m._hash(["failed-recovery-v1", parent_id, protocol, project,
                        session, inputs_sha])[:32]
    if (_row(evo, child_id) is not None or evo.db.execute(
            "SELECT 1 FROM knowledge_batches WHERE batch_id=?", (child_id,)).fetchone()):
        _fail("child already exists: " + child_id)
    return {
        "parent_id": parent_id, "child_id": child_id,
        "protocol": protocol, "project": project, "session": session,
        "source_ids": sorted(sids),
        "parent_sha": m._hash(dict(row)),
        "parent_preserved_sha": _preserved_sha(row),
        "inputs_sha": inputs_sha,
        "calls_hash": _calls_hash(evo, parent_id),
        "failures_hash": _failures_hash(evo, parent_id),
        "source_hash": m._hash(sources),
        "part_signatures": part_sigs,
        "claim_signatures": claim_sigs,
        "mandatory_cards": mandatory,
        "succession_depth": row.get("succession_depth") or 0,
    }


def prepare(evo, request):
    norm = _validate_request(request)
    entries = sorted((_prepare_entry(evo, pid) for pid in norm["work_ids"]),
                     key=lambda e: e["parent_id"])
    plan = {"protocol": _PROTOCOL, "request": norm, "entries": entries}
    plan["plan_sha"] = m._hash({k: v for k, v in plan.items() if k != "plan_sha"})
    return plan


def _plan_sha(plan):
    if not isinstance(plan, dict) or plan.get("protocol") != _PROTOCOL:
        _fail("bad plan")
    if set(plan) != {"protocol", "request", "entries", "plan_sha"}:
        _fail("bad plan shape")
    norm = _validate_request(plan.get('request'))
    if norm != plan['request']:
        _fail('noncanonical request')
    entries = plan.get('entries')
    if (not isinstance(entries, list) or not entries
            or any(not isinstance(e, dict) for e in entries)
            or [e.get('parent_id') for e in entries] != norm['work_ids']
            or any(not isinstance(e.get('child_id'), str) for e in entries)
            or len({e['child_id'] for e in entries}) != len(entries)):
        _fail('plan duty set mismatch')
    sha = plan.get("plan_sha")
    core = {k: v for k, v in plan.items() if k != "plan_sha"}
    if not isinstance(sha, str) or m._hash(core) != sha:
        _fail("bad plan hash")
    return sha


def apply(evo, plan):
    plan_sha = _plan_sha(plan)
    gid = plan["request"]["grant_id"]
    key = "failed_recovery_v1:" + gid
    with evo.engine.locked(), evo.engine.transaction():
        cur = evo.db.execute("SELECT value FROM meta WHERE key=?", (key,)).fetchone()
        if cur is not None:
            receipt = json.loads(cur["value"])
            if receipt.get("plan_sha") != plan_sha or receipt.get("plan") != plan:
                _fail("altered plan for grant: " + gid)
            out = dict(receipt)
            out["replayed"] = True
            return out
        fresh = prepare(evo, plan["request"])
        if fresh != plan:
            _fail("plan no longer matches reality")
        now = time.time()
        for e in plan["entries"]:
            pid, cid = e["parent_id"], e["child_id"]
            row = _row(evo, pid)
            if row is None or m._hash(dict(row)) != e["parent_sha"]:
                _fail("parent changed: " + pid)
            evo.db.execute(
                "INSERT INTO knowledge_work (id,project,session,inputs,state,"
                "created_at,succession_depth,pipeline_protocol) VALUES (?,?,?,?,?,?,?,?)",
                (cid, e["project"], e["session"], row["inputs"], "pending",
                 now, e["succession_depth"] + 1, e["protocol"]))
            claims = evo.db.execute(
                "SELECT source_id,version,part FROM knowledge_seen WHERE work_id=?",
                (pid,)).fetchall()
            for c in claims:
                cur = evo.db.execute(
                    "UPDATE knowledge_seen SET work_id=? WHERE work_id=? AND source_id=?"
                    " AND version=? AND part=?",
                    (cid, pid, c["source_id"], c["version"], c["part"]))
                if cur.rowcount != 1:
                    _fail("claim transfer failed: " + pid)
            cur = evo.db.execute(
                "UPDATE knowledge_work SET state='obsolete',lease_token=NULL,lease_until=0"
                " WHERE id=? AND state='failed' AND inputs=?",
                (pid, row["inputs"]))
            if cur.rowcount != 1:
                _fail("parent CAS failed: " + pid)
            blob = json.dumps({"plan_sha": plan_sha, "parent_id": pid, "child_id": cid},
                              sort_keys=True)
            evo.db.execute(
                "INSERT INTO knowledge_failures (work_id,state,error,created_at)"
                " VALUES (?,?,?,?)", (pid, _AUDIT_PARENT, blob, now))
            evo.db.execute(
                "INSERT INTO knowledge_failures (work_id,state,error,created_at)"
                " VALUES (?,?,?,?)", (cid, _AUDIT_CHILD, blob, now))
        receipt = {"grant_id": gid, "plan_sha": plan_sha, "plan": plan,
                   "applied_at": now, "replayed": False}
        evo.db.execute("INSERT INTO meta (key,value) VALUES (?,?)",
                       (key, json.dumps(receipt, sort_keys=True)))
        return receipt


def _completion_inputs(parts, sha_key):
    return sorted((p.get('source_id'), p.get('version'), p.get('part'), p.get(sha_key))
                  for p in parts)


def _verify_child_done(evo, e, crow):
    expected = _completion_inputs(e['part_signatures'], 'sha256')
    if e['protocol'] == m.V2_PROTOCOL:
        from . import delta_receipts
        result = delta_receipts.verify_completed(evo, crow['id'])
        if result['verified'] is not True:
            _fail('child completion not verified')
        # The operator's historical receipt binds source.parts, whereas auto
        # receipts bind owned_inputs. Interpret only an already-proven origin.
        from . import delta_operator
        receipt = result['receipt']
        if result.get('origin') == delta_operator.OPERATOR_ORIGIN:
            if receipt['origin'] != delta_operator.OPERATOR_ORIGIN:
                _fail('operator completion origin mismatch')
            source = receipt['source']
            actual = sorted((source['source_id'], source['version'],
                             part['part'], part['sha256'])
                            for part in source['parts'])
        else:
            actual = _completion_inputs(receipt['owned_inputs'], 'text_sha')
        # A receipt must cover exactly the inherited duty, not a subset.
        if actual != expected:
            _fail('completed child input mismatch')
        return True
    if e['protocol'] == m.LEGACY_PROTOCOL:
        from . import legacy_dependency_operator as ldo
        if ldo.has_legacy_operator_completion(evo, crow['id']):
            result = ldo.verify_completed(evo, crow['id'])
            if result['verified'] is not True:
                _fail('legacy operator completion not verified')
            actual = _completion_inputs(result['receipt']['owned_inputs'], 'text_sha')
            if actual != expected:
                _fail('completed child input mismatch')
            return True
    comps = _audits(evo, crow['id'], 'completion')
    if len(comps) != 1:
        return False
    audit = json.loads(comps[0]['error'])
    b = evo.db.execute('SELECT * FROM knowledge_batches WHERE batch_id=?',
                       (crow['id'],)).fetchone()
    if b is None or b['project'] != e['project']:
        return False
    if (_completion_inputs(audit.get('inputs') or [], 'sha256') != expected
            or audit.get('proposal_hash') != b['op_hash']):
        _fail('legacy completion not bound to inherited inputs/batch')
    changed = json.loads(b['changed_ids'])
    if sorted(changed) != audit.get('changed_ids'):
        return False
    return all(evo._published(cid) for cid in changed)


def verify(evo, grant_id):
    cur = evo.db.execute("SELECT value FROM meta WHERE key=?",
                         ("failed_recovery_v1:" + grant_id,)).fetchone()
    if cur is None:
        _fail("no receipt for grant: " + grant_id)
    receipt = json.loads(cur["value"])
    plan = receipt.get("plan")
    if receipt.get("plan_sha") != _plan_sha(plan):
        _fail("receipt plan hash mismatch")
    if receipt.get('grant_id') != grant_id or plan['request']['grant_id'] != grant_id:
        _fail('receipt grant mismatch')
    children = []
    for e in plan["entries"]:
        pid, cid = e["parent_id"], e["child_id"]
        prow = _row(evo, pid)
        if prow is None or prow["state"] != "obsolete" \
                or prow["lease_token"] is not None or (prow["lease_until"] or 0) != 0:
            _fail("parent not obsolete: " + pid)
        if _preserved_sha(prow) != e["parent_preserved_sha"]:
            _fail("parent preservation broken: " + pid)
        if _calls_hash(evo, pid) != e["calls_hash"]:
            _fail("calls changed: " + pid)
        rows = evo.db.execute(
            "SELECT rowid,* FROM knowledge_failures WHERE work_id=? ORDER BY rowid",
            (pid,)).fetchall()
        kept = [dict(r) for r in rows if r["state"] != _AUDIT_PARENT]
        removed = [dict(r) for r in rows if r["state"] == _AUDIT_PARENT]
        if len(removed) != 1 or m._hash(kept) != e["failures_hash"]:
            _fail("failures history changed: " + pid)
        paudit = json.loads(removed[0]["error"])
        expected_audit = {"plan_sha": plan["plan_sha"], "parent_id": pid, "child_id": cid}
        if paudit != expected_audit:
            _fail("bad parent audit: " + pid)
        caudits = _audits(evo, cid, _AUDIT_CHILD)
        if len(caudits) != 1 or json.loads(caudits[0]["error"]) != expected_audit:
            _fail("bad child audit: " + cid)
        crow = _row(evo, cid)
        if crow is None:
            _fail("missing child: " + cid)
        if crow["pipeline_protocol"] != e["protocol"] or crow["project"] != e["project"] \
                or crow["session"] != e["session"]:
            _fail("child identity mismatch: " + cid)
        claims = evo.db.execute(
            "SELECT source_id,version,part FROM knowledge_seen WHERE work_id=?",
            (cid,)).fetchall()
        sigs = sorted(m._hash([c["source_id"], c["version"], c["part"]])
                      for c in claims)
        if sigs != e["claim_signatures"]:
            _fail("claims not transferred: " + pid)
        complete = False
        if crow["state"] != "done" and m._hash(json.loads(crow["inputs"])) != e["inputs_sha"]:
            _fail("child inputs changed: " + cid)
        if crow["state"] == "done":
            complete = _verify_child_done(evo, e, crow)
        children.append({"parent_id": pid, "child_id": cid,
                         "state": crow["state"], "complete": complete})
    return {"verified": True,
            "complete": all(c["complete"] for c in children),
            "children": children}
